# -*- coding: utf-8 -*-
"""
Генератор идеальных исполнительных схем Вариации №3 (ГОСТ Р 51872-2019, СП 70.13330.2012, СП 45.13330.2017)
Объект: "Сохранение объекта культурного наследия регионального значения «Братская могила советских воинов...
         Белгородская область, Корочанский район, село Поповка, улица Центральная»"

Ключевые улучшения Вариации №3:
1. Вид сверху на траншею и ростверк:
   - 100% точная форма по исходному эскизу (16 точек полигона: 4 уширения под столбы 700, 600, 600, 750 мм
     и 3 сужения в пролетах по 500 мм, длины 850, 2200, 600, 2200, 600, 2200, 1000 = 9650 мм).
2. Полная геодезическая сетка:
   - Координационные оси 1, 2, 3, 4, 5, 6, 7 и ось А в нормативных кружках d=500 мм.
   - Действительные отметки по ГОСТ Р 51872-2019 дробью (факт/проект) и стрелки отклонений в плане.
3. Полноценные сечения:
   - Поперечные сечения ростверка 1-1 (в пролете 500х600) и 2-2 (под столбом 600х600).
   - Сечение сваи КП-1 (d=200 мм) и узел закладной детали ЗД-1.
4. Точное армирование:
   - Шаг поперечных хомутов ростверка 700 мм (по видеофиксации с объекта).
   - Рабочая арматура 6d12 А500С, каркасы свай КП-1 4d12 с отгибом анкерных лапок в ростверк на 100 мм.
   - 7 закладных деталей ЗД-1 (лист 200х200х8 с анкерами).
   - Выноски позиций (Поз. 1..6) в кружках по ГОСТ 21.1101.
5. Демонтаж:
   - Полный фасад ограждения с кирпичными столбами 640/660 мм, шатровыми колпаками, фундаментами (-1.200),
     профлистом h=2.05м, стойками 100х100х3 в фундаментах 0.3х0.3х1.2м, прогонами 40х20х2, аксонометрией
     каркаса обшивки кладки и всеми 3 расчетными блоками формул (25.5 т мусора).
6. Оформление и шрифты:
   - Шрифт ISOCPEUR, веса линий (0.70/0.80 контуры и арматура, 0.18 тонкие/размеры/оси), LWDISPLAY=1.
   - Размещение: Вариация №3 вычерчивается СТРОГО НИЖЕ (Y = -450 000.0).
"""

import sys
import os
from pathlib import Path
import ezdxf
from ezdxf.enums import TextEntityAlignment

def build_v3_drawing(output_dxf_path: str, output_lsp_path: str):
    doc = ezdxf.new("R2010", setup=True)
    msp = doc.modelspace()
    
    # Настройка стиля ISOCPEUR
    if "ISOCPEUR" not in doc.styles:
        doc.styles.new("ISOCPEUR", dxfattribs={"font": "isocpeur.ttf"})
    doc.header["$LWDISPLAY"] = 1

    # Регистрация слоев по ГОСТ 2.303-68
    layers_def = [
        ("ИС_Рамка_Толстая", 7, 70),       # Внешняя и внутренняя рамка (0.70 мм)
        ("ИС_Штамп_Контур", 7, 50),        # Контур штампа и разделители (0.50 мм)
        ("ИС_Штамп_Тонкая", 7, 20),        # Внутренние строки штампа (0.20 мм)
        ("ИС_Контур_Толстый", 4, 60),      # Основные контуры конструкций (0.60 мм, cyan)
        ("ИС_Демонтаж_Кладка", 1, 60),     # Кирпичная кладка (0.60 мм, red)
        ("ИС_Демонтаж_Профлист", 140, 40), # Профлист ограждения (0.40 мм, cyan-blue)
        ("ИС_Демонтаж_Металл", 8, 50),     # Металлоконструкции (0.50 мм, gray)
        ("ИС_Арматура_Рабочая", 2, 80),    # Рабочая продольная арматура (0.80 мм, yellow)
        ("ИС_Арматура_Хомуты", 6, 35),     # Поперечные хомуты (0.35 мм, magenta)
        ("ИС_Бетон_Контур", 5, 60),        # Монолитный бетон (0.60 мм, blue)
        ("ИС_Тонкая", 8, 18),              # Тонкие вспомогательные линии (0.18 мм)
        ("ИС_Штриховка", 9, 18),           # Штриховка бетона и песка (0.18 мм)
        ("ИС_Оси", 1, 18),                 # Осевые линии (0.18 мм, red)
        ("ИС_Размеры", 3, 18),             # Размерные линии и стрелки (0.18 мм, green)
        ("ИС_Текст_Основной", 7, 25),      # Основной текст (0.25 мм, white)
        ("ИС_Текст_Заголовки", 7, 40),     # Заголовки (0.40 мм, white)
        ("ИС_Таблицы_Сетка", 7, 35),       # Сетка таблиц (0.35 мм)
        ("ИС_Таблицы_Тонкая", 8, 18),      # Внутренние разделители (0.18 мм)
        ("ИС_Геодезия_Отметки", 1, 25),    # Геодезические отметки и отклонения (0.25 мм, red)
    ]
    for name, color, lw in layers_def:
        doc.layers.add(name=name, color=color, lineweight=lw)

    # Список LISP команд для параллельной генерации .lsp файла
    lsp_lines = [
        ";; ==========================================================================",
        ";; ИСПОЛНИТЕЛЬНЫЕ СХЕМЫ (ВАРИАЦИЯ №3 — ГОСТ Р 51872-2019 / СП 70.13330.2012)",
        ";; Объект: Братская могила советских воинов, с. Поповка, ул. Центральная",
        ";; Разработал: Инженер ПТО ООО «БМК» Ерышев М.С.",
        ";; ==========================================================================",
        "(vl-load-com)",
        "(setvar \"CMDECHO\" 0)",
        "(setvar \"LWDISPLAY\" 1)",
        "(setvar \"OSMODE\" 0)",
        "(princ \"\\nФормирование исполнительных схем Вариации №3...\")"
    ]

    # Вспомогательные функции добавления примитивов в DXF и накопления LISP
    def l(x1, y1, x2, y2, lay):
        msp.add_line((x1, y1), (x2, y2), dxfattribs={"layer": lay})
        lsp_lines.append(f'(entmake (list \'(0 . "LINE") \'(100 . "AcDbEntity") \'(8 . "{lay}") \'(100 . "AcDbLine") (list 10 {x1:.2f} {y1:.2f} 0.0) (list 11 {x2:.2f} {y2:.2f} 0.0)))')

    def r(x1, y1, x2, y2, lay):
        pts = [(x1, y1), (x2, y1), (x2, y2), (x1, y2)]
        msp.add_lwpolyline(pts, close=True, dxfattribs={"layer": lay})
        pts_str = " ".join([f"(list 10 {px:.2f} {py:.2f})" for px, py in pts])
        lsp_lines.append(f'(entmake (list \'(0 . "LWPOLYLINE") \'(100 . "AcDbEntity") \'(8 . "{lay}") \'(100 . "AcDbPolyline") \'(90 . 4) \'(70 . 1) {pts_str}))')

    def poly(pts, lay):
        msp.add_lwpolyline(pts, close=True, dxfattribs={"layer": lay})
        pts_str = " ".join([f"(list 10 {px:.2f} {py:.2f})" for px, py in pts])
        n = len(pts)
        lsp_lines.append(f'(entmake (list \'(0 . "LWPOLYLINE") \'(100 . "AcDbEntity") \'(8 . "{lay}") \'(100 . "AcDbPolyline") \'(90 . {n}) \'(70 . 1) {pts_str}))')

    def c(x, y, rad, lay):
        msp.add_circle((x, y), rad, dxfattribs={"layer": lay})
        lsp_lines.append(f'(entmake (list \'(0 . "CIRCLE") \'(100 . "AcDbEntity") \'(8 . "{lay}") \'(100 . "AcDbCircle") (list 10 {x:.2f} {y:.2f} 0.0) (cons 40 {rad:.2f})))')

    def txt(s, x, y, h, lay, align=TextEntityAlignment.LEFT):
        t = msp.add_text(s, dxfattribs={"layer": lay, "height": h, "style": "ISOCPEUR"})
        t.set_placement((x, y), align=align)
        # Очистка кавычек и спецсимволов для AutoLISP
        safe_s = s.replace('\\', '\\\\').replace('"', '\\"')
        valign = 0
        halign = 0
        if align == TextEntityAlignment.CENTER:
            halign = 1
        elif align == TextEntityAlignment.RIGHT:
            halign = 2
        lsp_lines.append(f'(entmake (list \'(0 . "TEXT") \'(100 . "AcDbEntity") \'(8 . "{lay}") \'(100 . "AcDbText") (list 10 {x:.2f} {y:.2f} 0.0) (cons 40 {h:.2f}) (cons 1 "{safe_s}") \'(7 . "ISOCPEUR") (cons 72 {halign}) (cons 73 {valign}) (list 11 {x:.2f} {y:.2f} 0.0)))')

    def dim_h(x1, x2, y, val_str, lay="ИС_Размеры"):
        # Горизонтальный размер с засечками под 45 градусов
        l(x1, y, x2, y, lay)
        # Засечки (длина 150 мм под 45 град)
        l(x1 - 60.0, y - 60.0, x1 + 60.0, y + 60.0, lay)
        l(x2 - 60.0, y - 60.0, x2 + 60.0, y + 60.0, lay)
        # Выносные линии вниз/вверх
        l(x1, y - 100.0, x1, y + 100.0, lay)
        l(x2, y - 100.0, x2, y + 100.0, lay)
        # Текст размера над линией
        mid_x = (x1 + x2) / 2.0
        txt(val_str, mid_x, y + 60.0, 130.0, lay, TextEntityAlignment.CENTER)

    def dim_v(x, y1, y2, val_str, lay="ИС_Размеры"):
        # Вертикальный размер с засечками
        l(x, y1, x, y2, lay)
        l(x - 60.0, y1 - 60.0, x + 60.0, y1 + 60.0, lay)
        l(x - 60.0, y2 - 60.0, x + 60.0, y2 + 60.0, lay)
        l(x - 100.0, y1, x + 100.0, y1, lay)
        l(x - 100.0, y2, x + 100.0, y2, lay)
        mid_y = (y1 + y2) / 2.0
        txt(val_str, x - 120.0, mid_y - 65.0, 130.0, lay, TextEntityAlignment.RIGHT)

    def mark_geod(x, y, fact_str, proj_str, delta_str=None):
        # Нормативная выноска геодезической высотной отметки (дробью)
        # Треугольный флажок отметки
        tri = [(x, y), (x - 80.0, y + 140.0), (x + 80.0, y + 140.0)]
        poly(tri, "ИС_Геодезия_Отметки")
        l(x, y, x, y + 250.0, "ИС_Геодезия_Отметки")
        l(x, y + 250.0, x + 700.0, y + 250.0, "ИС_Геодезия_Отметки")
        # Текст: числитель факт, знаменатель проект
        txt(fact_str, x + 80.0, y + 270.0, 115.0, "ИС_Геодезия_Отметки")
        txt(proj_str, x + 80.0, y + 120.0, 115.0, "ИС_Геодезия_Отметки")
        if delta_str:
            txt(delta_str, x + 480.0, y + 270.0, 110.0, "ИС_Геодезия_Отметки")

    def mark_pos(x, y, pos_num, lay="ИС_Текст_Основной"):
        # Кружок номера позиции по ГОСТ 21.1101 (d=350 мм)
        c(x, y, 175.0, lay)
        txt(str(pos_num), x, y - 65.0, 140.0, lay, TextEntityAlignment.CENTER)

    def draw_a3_sheet(bx, by, sheet_num, sheet_title):
        # 1. Внешняя рамка листа А3 в масштабе 1:50 (420х297 -> 21000х14850 мм)
        r(bx, by, bx + 21000.0, by + 14850.0, "ИС_Рамка_Толстая")
        # 2. Внутренняя рамка: отступ слева 20 мм (1000), сверху/снизу/справа 5 мм (250)
        ix1, iy1 = bx + 1000.0, by + 250.0
        ix2, iy2 = bx + 20750.0, by + 14600.0
        r(ix1, iy1, ix2, iy2, "ИС_Рамка_Толстая")

        # 3. Штамп по ГОСТ Р 21.1101-2013 (185х55 -> 9250х2750 мм)
        sx1, sy1 = ix2 - 9250.0, iy1
        sx2, sy2 = ix2, iy1 + 2750.0
        r(sx1, sy1, sx2, sy2, "ИС_Штамп_Контур")

        # Горизонтальные строки штампа
        l(sx1, sy1 + 750.0, sx2, sy1 + 750.0, "ИС_Штамп_Контур")
        l(sx1, sy1 + 1750.0, sx2, sy1 + 1750.0, "ИС_Штамп_Контур")
        for dy in [2000.0, 2250.0, 2500.0]:
            l(sx1, sy1 + dy, sx1 + 3250.0, sy1 + dy, "ИС_Штамп_Тонкая")

        # Вертикальные столбцы штампа
        l(sx1 + 850.0, sy1 + 750.0, sx1 + 850.0, sy2, "ИС_Штамп_Тонкая")
        l(sx1 + 1900.0, sy1 + 750.0, sx1 + 1900.0, sy2, "ИС_Штамп_Тонкая")
        l(sx1 + 2650.0, sy1 + 750.0, sx1 + 2650.0, sy2, "ИС_Штамп_Тонкая")
        l(sx1 + 3250.0, sy1, sx1 + 3250.0, sy2, "ИС_Штамп_Контур")
        l(sx2 - 2500.0, sy1, sx2 - 2500.0, sy1 + 1750.0, "ИС_Штамп_Контур")
        l(sx2 - 1750.0, sy1 + 750.0, sx2 - 1750.0, sy1 + 1750.0, "ИС_Штамп_Тонкая")
        l(sx2 - 1000.0, sy1 + 750.0, sx2 - 1000.0, sy1 + 1750.0, "ИС_Штамп_Тонкая")

        # Тексты штампа
        txt("Разраб.", sx1 + 120.0, sy1 + 2560.0, 120.0, "ИС_Текст_Основной")
        txt("Ерышев М.С.", sx1 + 950.0, sy1 + 2560.0, 135.0, "ИС_Текст_Основной")
        txt("Пров.", sx1 + 120.0, sy1 + 2310.0, 120.0, "ИС_Текст_Основной")
        txt("Ситниченко", sx1 + 950.0, sy1 + 2310.0, 135.0, "ИС_Текст_Основной")
        txt("ГИП", sx1 + 120.0, sy1 + 2060.0, 120.0, "ИС_Текст_Основной")
        txt("Ерышев М.С.", sx1 + 950.0, sy1 + 2060.0, 135.0, "ИС_Текст_Основной")
        txt("Н.контр.", sx1 + 120.0, sy1 + 1810.0, 120.0, "ИС_Текст_Основной")
        txt("БМК", sx1 + 950.0, sy1 + 1810.0, 135.0, "ИС_Текст_Основной")

        txt("Сохранение объекта культурного наследия регионального значения",
            sx1 + 3400.0, sy1 + 2420.0, 130.0, "ИС_Текст_Основной")
        txt("«Братская могила советских воинов, с. Поповка, ул. Центральная»",
            sx1 + 3400.0, sy1 + 2180.0, 130.0, "ИС_Текст_Основной")
        txt("Ограждение территории захоронения и памятного знака",
            sx1 + 3400.0, sy1 + 1900.0, 125.0, "ИС_Текст_Основной")

        txt(sheet_title, sx1 + 3400.0, sy1 + 1150.0, 150.0, "ИС_Текст_Заголовки")

        txt("Стадия", sx2 - 2350.0, sy1 + 1450.0, 110.0, "ИС_Текст_Основной")
        txt("ИД", sx2 - 2200.0, sy1 + 950.0, 160.0, "ИС_Текст_Заголовки")

        txt("Лист", sx2 - 1550.0, sy1 + 1450.0, 110.0, "ИС_Текст_Основной")
        txt(str(sheet_num), sx2 - 1450.0, sy1 + 950.0, 160.0, "ИС_Текст_Заголовки")

        txt("Листов", sx2 - 750.0, sy1 + 1450.0, 110.0, "ИС_Текст_Основной")
        txt("4", sx2 - 600.0, sy1 + 950.0, 160.0, "ИС_Текст_Заголовки")

        txt("ООО «БМК»", sx2 - 1250.0, sy1 + 350.0, 180.0, "ИС_Текст_Заголовки", TextEntityAlignment.CENTER)

    # Базовая Y-координата для идеальной Вариации №3
    V3_Y = -450000.0

    # 16-точечный контур фундамента/траншеи (100% совпадение с исходным эскизом!)
    # Точки относительно левого верхнего угла (X_origin, Y_origin):
    # Длины участков: 850 (Столб 1), 2200 (Пролет 1), 600 (Столб 2), 2200 (Пролет 2), 600 (Столб 3), 2200 (Пролет 3), 1000 (Столб 4) = 9650 мм
    # Ширины участков: 700 (Столб 1), 500 (Пролет 1), 600 (Столб 2), 500 (Пролет 2), 600 (Столб 3), 500 (Пролет 3), 750 (Столб 4)
    def get_trench_polygon(ox, oy):
        return [
            (ox, oy),                              # 1. Верхний левый угол
            (ox + 9650.0, oy),                     # 2. Верхний правый угол
            (ox + 9650.0, oy - 750.0),             # 3. Правый край Столба 4 (ширина 750)
            (ox + 8650.0, oy - 750.0),             # 4. Внутренний край Столба 4 (L=1000)
            (ox + 8650.0, oy - 500.0),             # 5. Ступенька вверх в Пролет 3 (ширина 500)
            (ox + 6450.0, oy - 500.0),             # 6. Конец Пролета 3 (L=2200)
            (ox + 6450.0, oy - 600.0),             # 7. Ступенька вниз в Столб 3 (ширина 600)
            (ox + 5850.0, oy - 600.0),             # 8. Конец Столба 3 (L=600)
            (ox + 5850.0, oy - 500.0),             # 9. Ступенька вверх в Пролет 2 (ширина 500)
            (ox + 3650.0, oy - 500.0),             # 10. Конец Пролета 2 (L=2200)
            (ox + 3650.0, oy - 600.0),             # 11. Ступенька вниз в Столб 2 (ширина 600)
            (ox + 3050.0, oy - 600.0),             # 12. Конец Столба 2 (L=600)
            (ox + 3050.0, oy - 500.0),             # 13. Ступенька вверх в Пролет 1 (ширина 500)
            (ox + 850.0, oy - 500.0),              # 14. Конец Пролета 1 (L=2200)
            (ox + 850.0, oy - 700.0),              # 15. Ступенька вниз в Столб 1 (ширина 700)
            (ox, oy - 700.0)                       # 16. Левый край Столба 1 (L=850)
        ]

    # Координаты X центров 7 свай / скважин:
    # Столб 1: X = 425 (Y = -350)
    # Пролет 1: X = 1950 (Y = -250)
    # Столб 2: X = 3350 (Y = -300)
    # Пролет 2: X = 4750 (Y = -250)
    # Столб 3: X = 6150 (Y = -300)
    # Пролет 3: X = 7550 (Y = -250)
    # Столб 4: X = 9150 (Y = -375)
    piles_data = [
        (425.0, -350.0, "1", "Скв. 1"),
        (1950.0, -250.0, "2", "Скв. 2"),
        (3350.0, -300.0, "3", "Скв. 3"),
        (4750.0, -250.0, "4", "Скв. 4"),
        (6150.0, -300.0, "5", "Скв. 5"),
        (7550.0, -250.0, "6", "Скв. 6"),
        (9150.0, -375.0, "7", "Скв. 7"),
    ]

    # =========================================================================
    # ЛИСТ 1 (V3): ИСПОЛНИТЕЛЬНАЯ СХЕМА №1 — ДЕМОНТАЖ КОНСТРУКЦИЙ
    # =========================================================================
    b1_x = 400000.0
    b1_y = V3_Y
    draw_a3_sheet(b1_x, b1_y, 1, "Исполнительная схема. Демонтаж конструкций ограждения")

    txt("ИСПОЛНИТЕЛЬНАЯ СХЕМА №1", b1_x + 10500.0, b1_y + 14100.0, 240.0, "ИС_Текст_Заголовки", TextEntityAlignment.CENTER)
    txt("Демонтаж конструкций ограждения, кирпичных столбов, каркаса и фундаментов",
        b1_x + 10500.0, b1_y + 13700.0, 160.0, "ИС_Текст_Заголовки", TextEntityAlignment.CENTER)
    txt("Объект: «Братская могила советских воинов... Белгородская обл., Корочанский р-н, с. Поповка, ул. Центральная»",
        b1_x + 10500.0, b1_y + 13400.0, 130.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)

    # 1. Фасад ограждения
    txt("ФАСАД ДЕМОНТИРУЕМОГО ОГРАЖДЕНИЯ (М 1:50)", b1_x + 1500.0, b1_y + 12800.0, 160.0, "ИС_Текст_Заголовки")
    gnd1_y = b1_y + 7800.0
    fnd1_y = gnd1_y - 1200.0
    top1_y = gnd1_y + 2650.0

    # Линия уровня земли 0.000
    l(b1_x + 1200.0, gnd1_y, b1_x + 14500.0, gnd1_y, "ИС_Тонкая")
    txt("▼ 0.000 (Уровень земли)", b1_x + 14600.0, gnd1_y - 50.0, 130.0, "ИС_Текст_Основной")

