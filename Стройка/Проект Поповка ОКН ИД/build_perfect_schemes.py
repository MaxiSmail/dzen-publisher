# -*- coding: utf-8 -*-
"""
Полноценный генератор обновленных исполнительных схем (с учетом замечаний пользователя):
1. Схема демонтажа перерисована ПОЛНОСТЬЮ:
   - Фасад ограждения с кирпичными столбами, жестяными колпаками, фундаментами (-1.200)
   - Пролеты с профлистом (h=2.05м), каркасом 40х20х2, стойками 100х100х3 в фундаментах 0.3х0.3х1.2м
   - Аксонометрический узел каркаса обшивки кладки
   - Все 3 блока формул и расчетов в точности по исходной схеме
2. Шрифты: ГОСТ шрифт ISOCPEUR, строгие отступы и вертикальное центрирование, исключение наездов.
3. Вес линий: строгая дифференциация (0.60/0.70 - контуры и арматура, 0.18 - размеры, оси, штриховки).
   Включение LWDISPLAY=1.
4. Размещение: исходные чертежи сохранены, новые исправленные вычерчиваются НИЖЕ (Y = -430000).
"""

import os
from pathlib import Path
import ezdxf
from ezdxf.enums import TextEntityAlignment

def generate_perfect_dxf(output_path: str):
    doc = ezdxf.new("R2010", setup=True)
    msp = doc.modelspace()
    
    # Настройка стиля текста ISOCPEUR
    if "ISOCPEUR" not in doc.styles:
        doc.styles.new("ISOCPEUR", dxfattribs={"font": "isocpeur.ttf"})
    doc.header["$LWDISPLAY"] = 1  # Включаем отображение весов линий

    # Слои с точными весами линий по ГОСТ 2.303-68
    layers = [
        ("ИС_Рамка_Толстая", 7, 70),       # Внешняя и внутренняя рамка (0.70 мм)
        ("ИС_Штамп_Контур", 7, 50),        # Контур штампа и основные разделители (0.50 мм)
        ("ИС_Штамп_Тонкая", 7, 20),        # Внутренние строки штампа (0.20 мм)
        ("ИС_Контур_Толстый", 4, 60),      # Основные контуры конструкций (0.60 мм)
        ("ИС_Демонтаж_Кладка", 1, 60),     # Кирпичные столбы демонтажа (0.60 мм)
        ("ИС_Демонтаж_Профлист", 140, 40), # Профлист демонтажа (голубой, 0.40 мм)
        ("ИС_Демонтаж_Металл", 8, 50),     # Металлоконструкции (0.50 мм)
        ("ИС_Арматура_Рабочая", 2, 70),    # Рабочая продольная арматура (0.70 мм)
        ("ИС_Арматура_Хомуты", 6, 35),     # Поперечные хомуты (0.35 мм)
        ("ИС_Бетон_Контур", 5, 60),        # Монолитный бетон (0.60 мм)
        ("ИС_Тонкая", 8, 18),              # Вспомогательные тонкие линии (0.18 мм)
        ("ИС_Оси", 1, 18),                 # Осевые линии (0.18 мм)
        ("ИС_Размеры", 3, 18),             # Размерные линии и стрелки (0.18 мм)
        ("ИС_Текст_Основной", 7, 25),      # Основной текст (0.25 мм)
        ("ИС_Таблицы_Сетка", 7, 35),       # Сетка таблиц (0.35 мм)
        ("ИС_Таблицы_Тонкая", 8, 18),      # Внутренние разделители (0.18 мм)
    ]
    for name, color, lw in layers:
        doc.layers.add(name=name, color=color, lineweight=lw)

    # Примитивы
    def l(x1, y1, x2, y2, lay):
        msp.add_line((x1, y1), (x2, y2), dxfattribs={"layer": lay})

    def r(x1, y1, x2, y2, lay):
        pts = [(x1, y1), (x2, y1), (x2, y2), (x1, y2)]
        msp.add_lwpolyline(pts, close=True, dxfattribs={"layer": lay})

    def c(x, y, rad, lay):
        msp.add_circle((x, y), rad, dxfattribs={"layer": lay})

    def txt(s, x, y, h, lay, align=TextEntityAlignment.LEFT, bold=False):
        t = msp.add_text(s, dxfattribs={"layer": lay, "height": h, "style": "ISOCPEUR"})
        t.set_placement((x, y), align=align)

    def draw_a3_frame(bx, by, sheet_num, sheet_title):
        # 1. Рамка листа А3 (21000 х 14850)
        r(bx, by, bx + 21000.0, by + 14850.0, "ИС_Рамка_Толстая")
        ix1, iy1 = bx + 1000.0, by + 250.0
        ix2, iy2 = bx + 20750.0, by + 14600.0
        r(ix1, iy1, ix2, iy2, "ИС_Рамка_Толстая")

        # 2. Штамп по ГОСТ (185х55 -> 9250х2750 мм)
        sx1, sy1 = ix2 - 9250.0, iy1
        sx2, sy2 = ix2, iy1 + 2750.0
        r(sx1, sy1, sx2, sy2, "ИС_Штамп_Контур")

        # Горизонтальные линии штампа
        l(sx1, sy1 + 750.0, sx2, sy1 + 750.0, "ИС_Штамп_Контур")
        l(sx1, sy1 + 1750.0, sx2, sy1 + 1750.0, "ИС_Штамп_Контур")
        for dy in [2000.0, 2250.0, 2500.0]:
            l(sx1, sy1 + dy, sx1 + 3250.0, sy1 + dy, "ИС_Штамп_Тонкая")

        # Вертикальные линии штампа
        l(sx1 + 850.0, sy1 + 750.0, sx1 + 850.0, sy2, "ИС_Штамп_Тонкая")
        l(sx1 + 1900.0, sy1 + 750.0, sx1 + 1900.0, sy2, "ИС_Штамп_Тонкая")
        l(sx1 + 2650.0, sy1 + 750.0, sx1 + 2650.0, sy2, "ИС_Штамп_Тонкая")
        l(sx1 + 3250.0, sy1, sx1 + 3250.0, sy2, "ИС_Штамп_Контур")
        l(sx2 - 2500.0, sy1, sx2 - 2500.0, sy1 + 1750.0, "ИС_Штамп_Контур")
        l(sx2 - 1750.0, sy1 + 750.0, sx2 - 1750.0, sy1 + 1750.0, "ИС_Штамп_Тонкая")
        l(sx2 - 1000.0, sy1 + 750.0, sx2 - 1000.0, sy1 + 1750.0, "ИС_Штамп_Тонкая")

        # Тексты штампа
        txt("Разраб.", sx1 + 120.0, sy1 + 2560.0, 120.0, "ИС_Текст_Основной")
        txt("Ерышев М.С.", sx1 + 950.0, sy1 + 2560.0, 135.0, "ИС_Текст_Основной")
        txt("Пров.", sx1 + 120.0, sy1 + 2310.0, 120.0, "ИС_Текст_Основной")
        txt("ГИП", sx1 + 120.0, sy1 + 2060.0, 120.0, "ИС_Текст_Основной")
        txt("Н.контр.", sx1 + 120.0, sy1 + 1810.0, 120.0, "ИС_Текст_Основной")

        txt("Сохранение объекта культурного наследия регионального значения",
            sx1 + 3400.0, sy1 + 2420.0, 145.0, "ИС_Текст_Основной")
        txt("«Братская могила советских воинов, 1967 г.». Белгородская обл., с. Поповка",
            sx1 + 3400.0, sy1 + 2100.0, 140.0, "ИС_Текст_Основной")
        txt(sheet_title, sx1 + 3400.0, sy1 + 1300.0, 170.0, "ИС_Текст_Основной")

        txt("Стадия", sx2 - 2125.0, sy1 + 1450.0, 100.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
        txt("ИД", sx2 - 2125.0, sy1 + 1050.0, 150.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
        txt("Лист", sx2 - 1375.0, sy1 + 1450.0, 100.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
        txt(str(sheet_num), sx2 - 1375.0, sy1 + 1050.0, 150.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
        txt("Листов", sx2 - 500.0, sy1 + 1450.0, 100.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
        txt("4", sx2 - 500.0, sy1 + 1050.0, 150.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
        txt("ООО «БМК»", sx2 - 1250.0, sy1 + 320.0, 220.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)

        # Верхний штамп согласования АОСР
        r(ix2 - 4000.0, iy2 - 900.0, ix2, iy2, "ИС_Штамп_Контур")
        txt("к АОСР № _____ от «____» __________ 2026 г.", ix2 - 3850.0, iy2 - 550.0, 135.0, "ИС_Текст_Основной")

    # Базовая Y-координата для НОВЫХ исправленных чертежей
    BASE_Y = -430000.0

    # =========================================================================
    # ЛИСТ 1 (НОВЫЙ): ИС №1 — ДЕМОНТАЖ КОНСТРУКЦИЙ (ПОЛНЫЙ РЕДИЗАЙН 1:1)
    # =========================================================================
    b1_x = 400000.0
    b1_y = BASE_Y
    draw_a3_frame(b1_x, b1_y, 1, "Исполнительная схема. Демонтаж конструкций ограждения и фундаментов")

    # Заголовок
    txt("Исполнительная схема №1", b1_x + 10500.0, b1_y + 14100.0, 240.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("Демонтаж конструкций на объекте: \"Сохранение объекта культурного наследия регионального значения «Братская могила советских воинов,",
        b1_x + 10500.0, b1_y + 13700.0, 140.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("погибших в боях с фашистскими захватчиками в 1943 году. Захоронено 38 человек, имена 3 человек установлены. Скульптура советского воина», 1967 г.,",
        b1_x + 10500.0, b1_y + 13400.0, 130.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("Белгородская область, Корочанский район, село Поповка, улица Центральная\"",
        b1_x + 10500.0, b1_y + 13100.0, 130.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)

    # Координаты фасада
    # Отметки
    gnd_y = b1_y + 7500.0
    fnd_y = gnd_y - 1200.0
    top_y = gnd_y + 2650.0

    # Линия уровня земли
    l(b1_x + 1200.0, gnd_y, b1_x + 15500.0, gnd_y, "ИС_Тонкая")
    # Стрелка и подпись Уровень земли 0.000
    txt("Уровень земли 0.000", b1_x + 15600.0, gnd_y + 350.0, 130.0, "ИС_Текст_Основной")
    l(b1_x + 15800.0, gnd_y + 300.0, b1_x + 15800.0, gnd_y, "ИС_Тонкая")
    l(b1_x + 15750.0, gnd_y + 100.0, b1_x + 15800.0, gnd_y, "ИС_Тонкая")
    l(b1_x + 15850.0, gnd_y + 100.0, b1_x + 15800.0, gnd_y, "ИС_Тонкая")

    # Линия низа оснований фундаментов -1.200
    l(b1_x + 1200.0, fnd_y, b1_x + 14000.0, fnd_y, "ИС_Тонкая")
    txt("Низ основания", b1_x + 9000.0, fnd_y - 250.0, 130.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("фундаментов -1.200", b1_x + 9000.0, fnd_y - 450.0, 130.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    l(b1_x + 10100.0, fnd_y - 400.0, b1_x + 10100.0, fnd_y, "ИС_Тонкая")
    l(b1_x + 10050.0, fnd_y - 100.0, b1_x + 10100.0, fnd_y, "ИС_Тонкая")
    l(b1_x + 10150.0, fnd_y - 100.0, b1_x + 10100.0, fnd_y, "ИС_Тонкая")

    # Стрелка Верх демонтируемой конструкции +2.650
    txt("Верх демонтируемой", b1_x + 6500.0, top_y + 600.0, 130.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("конструкции +2.650", b1_x + 6500.0, top_y + 400.0, 130.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    l(b1_x + 6500.0, top_y + 350.0, b1_x + 6500.0, top_y, "ИС_Тонкая")
    l(b1_x + 6450.0, top_y + 100.0, b1_x + 6500.0, top_y, "ИС_Тонкая")
    l(b1_x + 6550.0, top_y + 100.0, b1_x + 6500.0, top_y, "ИС_Тонкая")

    # Отрисовка 4-х столбов и пролетов по исходному эскизу
    # Столб 1: x_start = 2200, width = 640
    # Пролет 1: width = 1450
    # Столб 2: width = 640
    # Пролет 2: width = 970
    # Столб 3: width = 660
    # Пролет 3: width = 1030
    # Столб 4: width = 640
    # Боковой пролет: width = 1450
    cur_x = b1_x + 2200.0

    def draw_pillar(px, pw, cap_h=550.0):
        # Фундамент под столбом
        r(px, fnd_y, px + pw, gnd_y, "ИС_Демонтаж_Кладка")
        # Кладка столба
        r(px, gnd_y, px + pw, top_y, "ИС_Демонтаж_Кладка")
        # Центральная вертикальная накладка/полоса
        r(px + pw / 2.0 - 25.0, gnd_y, px + pw / 2.0 + 25.0, top_y, "ИС_Демонтаж_Металл")
        # Металлический шатровый колпак из жести
        peak_x = px + pw / 2.0
        peak_y = top_y + cap_h
        pts_cap = [(px - 80.0, top_y), (peak_x, peak_y), (px + pw + 80.0, top_y)]
        msp.add_lwpolyline(pts_cap, close=True, dxfattribs={"layer": "ИС_Демонтаж_Кладка"})
        l(peak_x, peak_y, peak_x, top_y, "ИС_Тонкая")

    def draw_span(sx, sw):
        # 1. Профлист (голубой, h=2050 от земли)
        sheet_top = gnd_y + 2050.0
        r(sx, gnd_y, sx + sw, sheet_top, "ИС_Демонтаж_Профлист")
        # Горизонтальные направляющие из профтрубы 40*20*2 (на отм. +0.40, +1.025, +1.80)
        l(sx, gnd_y + 400.0, sx + sw, gnd_y + 400.0, "ИС_Демонтаж_Металл")
        l(sx, gnd_y + 1025.0, sx + sw, gnd_y + 1025.0, "ИС_Демонтаж_Металл")
        l(sx, gnd_y + 1800.0, sx + sw, gnd_y + 1800.0, "ИС_Демонтаж_Металл")
        # 2. Профильная труба 100*100*3 по центру пролета (от -1.200 до +2.650)
        post_x = sx + sw / 2.0
        r(post_x - 50.0, fnd_y, post_x + 50.0, top_y, "ИС_Демонтаж_Металл")
        # 3. Фундамент стойки 0.3*0.3*1.2 (ширина 300 на фасаде)
        r(post_x - 150.0, fnd_y, post_x + 150.0, gnd_y, "ИС_Демонтаж_Кладка")

    # Вычерчиваем цепочку
    # 1. Столб 1 (640)
    p1_x = cur_x
    draw_pillar(p1_x, 640.0)
    txt("Металлический", p1_x + 320.0, top_y + 1200.0, 110.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("колпак из жести", p1_x + 320.0, top_y + 1050.0, 110.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    l(p1_x + 320.0, top_y + 1000.0, p1_x + 320.0, top_y + 550.0, "ИС_Тонкая")
    cur_x += 640.0

    # 2. Пролет 1 (1450)
    s1_x = cur_x
    draw_span(s1_x, 1450.0)
    cur_x += 1450.0

    # 3. Столб 2 (640)
    p2_x = cur_x
    draw_pillar(p2_x, 640.0)
    cur_x += 640.0

    # 4. Пролет 2 (970)
    s2_x = cur_x
    draw_span(s2_x, 970.0)
    # Выноска на профтрубу 100*100
    txt("Профильная труба", s2_x + 485.0, top_y + 700.0, 120.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("100*100", s2_x + 485.0, top_y + 520.0, 120.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    l(s2_x + 485.0, top_y + 480.0, s2_x + 485.0, top_y + 50.0, "ИС_Тонкая")
    cur_x += 970.0

    # 5. Столб 3 (660)
    p3_x = cur_x
    draw_pillar(p3_x, 660.0)
    cur_x += 660.0

    # 6. Пролет 3 (1030)
    s3_x = cur_x
    draw_span(s3_x, 1030.0)
    # Выноска на профтрубу 40*20*2
    txt("Проф труба 40*20*2", s3_x + 515.0, top_y + 800.0, 120.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    l(s3_x + 515.0, top_y + 750.0, s3_x + 515.0, gnd_y + 1800.0, "ИС_Тонкая")
    # Выноска на фундаменты профильных труб
    txt("Фундаменты", s3_x + 515.0, fnd_y - 650.0, 120.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("профильных труб", s3_x + 515.0, fnd_y - 820.0, 120.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("Размер фундамента", s3_x + 515.0, fnd_y - 1050.0, 110.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("0,3*0,3*1,2", s3_x + 515.0, fnd_y - 1220.0, 110.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    l(s3_x + 515.0, fnd_y - 600.0, s3_x + 515.0, fnd_y + 300.0, "ИС_Тонкая")
    cur_x += 1030.0

    # 7. Столб 4 (640)
    p4_x = cur_x
    draw_pillar(p4_x, 640.0)
    cur_x += 640.0

    # 8. Боковой пролет (1450)
    s4_x = cur_x
    draw_span(s4_x, 1450.0)
    cur_x += 1450.0

    # Размерная линия по низу
    dim_y = fnd_y - 350.0
    l(p1_x, dim_y, cur_x, dim_y, "ИС_Размеры")
    dims_demo = [
        (p1_x, 640), (s1_x, 1450), (p2_x, 640), (s2_x, 970),
        (p3_x, 660), (s3_x, 1030), (p4_x, 640), (s4_x, 1450)
    ]
    for dx_start, dw in dims_demo:
        l(dx_start, dim_y - 80.0, dx_start, dim_y + 80.0, "ИС_Размеры")
        txt(str(dw), dx_start + dw / 2.0, dim_y - 220.0, 120.0, "ИС_Размеры", TextEntityAlignment.CENTER)
    l(cur_x, dim_y - 80.0, cur_x, dim_y + 80.0, "ИС_Размеры")

    # АКСОНОМЕТРИЧЕСКИЙ УЗЕЛ КАРКАСА (справа вверху, в точности как на эскизе!)
    iso_x = b1_x + 16200.0
    iso_y = b1_y + 9500.0
    txt("Каркас обшивки", iso_x + 600.0, iso_y + 3200.0, 140.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("кладки проф трубой", iso_x + 600.0, iso_y + 3000.0, 140.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)
    txt("40*20*2", iso_x + 600.0, iso_y + 2800.0, 140.0, "ИС_Текст_Основной", TextEntityAlignment.CENTER)

    # 3D параллелепипед каркаса
    # Передняя грань
    r(iso_x, iso_y, iso_x + 600.0, iso_y + 2400.0, "ИС_Контур_Толстый")
    l(iso_x, iso_y + 800.0, iso_x + 600.0, iso_y + 800.0, "ИС_Демонтаж_Металл")
    l(iso_x, iso_y + 1600.0, iso_x + 600.0, iso_y + 1600.0, "ИС_Демонтаж_Металл")
    # Задняя грань (со смещением dx=400, dy=400)
    dx_iso, dy_iso = 400.0, 400.0
    r(iso_x + dx_iso, iso_y + dy_iso, iso_x + 600.0 + dx_iso, iso_y + 2400.0 + dy_iso, "ИС_Тонкая")
    # Соединяющие ребра
    l(iso_x, iso_y, iso_x + dx_iso, iso_y + dy_iso, "ИС_Тонкая")
    l(iso_x + 600.0, iso_y, iso_x + 600.0 + dx_iso, iso_y + dy_iso, "ИС_Контур_Толстый")
